const UNKNOWN: string[] = ["###", "###", "###", "###", "###"];

export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + 1) - 1;
}

/**
 * Draw text (uppercased) with its top-left at (x, y) using the given CSS
 * color. Pixels only — no antialiasing, palette stays intact.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  text: string,
  color: string,
): void {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const raw of text.toUpperCase()) {
    const glyph = GLYPHS[raw] ?? UNKNOWN;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = glyph[r] ?? "";
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === "#") ctx.fillRect(cx + c, cy + r, 1, 1);
      }
    }
    cx += GLYPH_W + 1;
  }
}
